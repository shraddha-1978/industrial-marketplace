export const getProductById = (id) => products.find((p) => p.id === id)

export const getProductsByCategory = (categoryId) =>
  products.filter((p) => p.categoryId === categoryId)

export const getProductsBySupplier = (supplierId) =>
  products.filter((p) => p.supplierId === supplierId)

export const getFeaturedProducts = () => products.filter((p) => p.featured)

// Distinct brands across the catalogue, used by the catalogue filter panel.
export const brands = [...new Set(products.map((p) => p.brand))].sort()

// Price bounds used by the catalogue range filter.
export const priceBounds = products.reduce(
  (acc, p) => ({
    min: Math.min(acc.min, p.price),
    max: Math.max(acc.max, p.price),
  }),
  { min: Infinity, max: 0 },
)
